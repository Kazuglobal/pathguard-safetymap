/** Codex に渡すプロンプト（1枚分）。 */
export function composePrompt(ep, key) {
  const item = IMAGES[ep]?.[key]
  if (!item) throw new Error(`EP${ep} の ${key} のプロンプトがない`)
  return `${SIZE[ORIENT[key]]}の写真を1枚。${item.prompt}\n${STYLE}\n${MOOD[key]}\n${RULES}`
}
